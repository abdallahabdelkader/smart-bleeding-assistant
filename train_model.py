"""Train a toy softmax classifier on explicitly synthetic rule-labelled examples.
No clinical data. Standard-library Python only. Run: python train_model.py
"""
import csv, json, math
from pathlib import Path
ROOT = Path(__file__).resolve().parent
CLASSES = ['mild', 'nose', 'embedded', 'severe_limb', 'severe_body']
FEATURES = ['amount_mild','amount_nose','amount_severe','object_no','object_yes','limb_no','limb_yes']
def encode(a):
    return [int(a['amount']==v) for v in ['mild','nose','severe']] + [int(a['object']==v) for v in ['no','yes']] + [int(a['limb']==v) for v in ['no','yes']]
rows=list(csv.DictReader((ROOT/'synthetic-training.csv').open()))
X=[encode(a) for a in rows]; Y=[CLASSES.index(a['label']) for a in rows]
W=[[0.0]*7 for _ in CLASSES]; B=[0.0]*5
for epoch in range(4000):
    dw=[[0.0]*7 for _ in CLASSES]; db=[0.0]*5
    for x,y in zip(X,Y):
        z=[sum(w*v for w,v in zip(wc,x))+b for wc,b in zip(W,B)]
        e=[math.exp(v-max(z)) for v in z]; p=[v/sum(e) for v in e]
        for c in range(5):
            d=p[c]-int(c==y); db[c]+=d/len(X)
            for j in range(7): dw[c][j]+=d*x[j]/len(X)
    for c in range(5):
        B[c]-=0.3*db[c]
        for j in range(7): W[c][j]-=0.3*dw[c][j]
model={'version':1,'algorithm':'multinomial logistic regression (softmax)','classes':CLASSES,'features':FEATURES,'weights':W,'bias':B,'training_rows':len(rows),'epochs':4000,'learning_rate':0.3,'data':'synthetic, rule-labelled; no patient data'}
(ROOT/'model-weights.js').write_text('/* Generated by train_model.py. Educational model, not clinically validated. */\nwindow.BLEEDING_MODEL = '+json.dumps(model,separators=(',',':'))+';\n')
print('Exported model-weights.js from',len(rows),'synthetic examples. No clinical evaluation.')
